# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                     PACKAGE MANAGER DETECTION
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
detect_package_manager() {
    if [[ "$OS" == "Darwin" ]]; then
        PKG_MGR="brew"
        return
    fi
    for cmd in apt-get dnf pacman apk zypper; do
        if command -v "$cmd" &>/dev/null; then
            PKG_MGR="$cmd"
            return
        fi
    done
    log_err "No supported package manager found (apt-get, dnf, pacman, apk, zypper, brew)."
    exit 1
}

setup_sudo() {
    if [[ "$OS" != "Darwin" ]] && command -v sudo &>/dev/null; then
        SUDO="sudo"
    fi
}

pkg_install() {
    local pkgs=("$@")
    case "$PKG_MGR" in
        brew)
            for p in "${pkgs[@]}"; do
                brew list --formula "$p" &>/dev/null || brew install "$p"
            done
            ;;
        apt-get)
            $SUDO apt-get update -qq
            $SUDO DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends "${pkgs[@]}"
            ;;
        dnf)
            $SUDO dnf install -y "${pkgs[@]}"
            ;;
        pacman)
            $SUDO pacman -Sy --noconfirm --needed "${pkgs[@]}"
            ;;
        apk)
            $SUDO apk add --no-cache "${pkgs[@]}"
            ;;
        zypper)
            $SUDO zypper install -y "${pkgs[@]}"
            ;;
    esac
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                HOMEBREW (MACOS ONLY) — MUST HAPPEN BEFORE ANYTHING CALLS BREW
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
ensure_homebrew() {
    [[ "$OS" == "Darwin" ]] || return 0
    if ! command -v brew &>/dev/null; then
        log_step "Installing Homebrew..."
        NONINTERACTIVE=1 /bin/bash -c \
            "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
        if   [[ -x /opt/homebrew/bin/brew ]]; then eval "$(/opt/homebrew/bin/brew shellenv)"
        elif [[ -x /usr/local/bin/brew    ]]; then eval "$(/usr/local/bin/brew shellenv)"
        fi
    fi
    log_ok "Homebrew is installed."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                           GENERIC TOOL INSTALLER (idempotent)
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
ensure_tool() {
    local tool="$1" pkg="${2:-$1}"
    if command -v "$tool" &>/dev/null; then
        log_ok "$tool is already installed."
        return
    fi
    log_step "Installing $tool..."
    pkg_install "$pkg"
    log_ok "$tool is installed."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                                     GHOSTTY
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
# Ghostty only distributes official prebuilt binaries for macOS. Everything in
# the Linux branch below is either a distro package or a community build, which
# is why this is a case statement and not a pkg_install one-liner.
install_ghostty() {
    if command -v ghostty &>/dev/null; then
        log_ok "ghostty is already installed."
        GHOSTTY_INSTALLED=1
        return
    fi

    log_step "Installing ghostty..."
    case "$PKG_MGR" in
        brew)
            # Cask, not formula — Ghostty is a .app bundle.
            brew install --cask ghostty
            ;;
        apt-get)
            # In the Ubuntu archive from 26.04 onward; before that there is no
            # distro package, so fall back to the community Snap.
            $SUDO apt-get update -qq
            if $SUDO DEBIAN_FRONTEND=noninteractive apt-get install -y ghostty 2>/dev/null; then
                :
            elif command -v snap &>/dev/null; then
                log_info "No ghostty package in this release's archive; using the Snap."
                $SUDO snap install ghostty --classic
            else
                log_err "No ghostty package for this release and snapd is not installed.
         Install snapd and rerun, or grab a .deb from
         https://github.com/mkasberg/ghostty-ubuntu/releases"
                exit 1
            fi
            ;;
        dnf)
            # Community COPR; `dnf copr` lives in dnf-plugins-core.
            $SUDO dnf install -y dnf-plugins-core
            $SUDO dnf copr enable -y scottames/ghostty
            $SUDO dnf install -y ghostty
            ;;
        pacman)
            $SUDO pacman -Sy --noconfirm --needed ghostty
            ;;
        apk)
            # Ghostty lives in the testing repository.
            $SUDO apk add --no-cache ghostty || \
                $SUDO apk add --no-cache --repository=https://dl-cdn.alpinelinux.org/alpine/edge/testing ghostty
            ;;
        zypper)
            $SUDO zypper install -y ghostty
            ;;
    esac

    if ! command -v ghostty &>/dev/null && [[ "$OS" != "Darwin" ]]; then
        log_err "ghostty did not land on PATH. Check the package manager output above."
        exit 1
    fi
    GHOSTTY_INSTALLED=1
    log_ok "ghostty is installed."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                              EXAMPLE CONFIG
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
backup_file() {
    local f="$1" backup
    [[ -f "$f" ]] || return 0
    backup="$f.pre-ghostty.$(date +%Y%m%d-%H%M%S).bak"
    cp "$f" "$backup"
    log_info "Backed up $f → $backup"
}

write_example_config() {
    local tmp
    tmp="$(mktemp)"

    log_step "Fetching the example config from itdojo/qol..."
    if ! curl -fsSL "$CONFIG_URL" -o "$tmp"; then
        rm -f "$tmp"
        log_warn "Could not download the example config; ghostty will use its defaults.
         Grab it later from $CONFIG_URL"
        return 0
    fi

    if [[ -f "$CONFIG_FILE" ]] && cmp -s "$tmp" "$CONFIG_FILE"; then
        rm -f "$tmp"
        log_ok "$CONFIG_FILE is already up to date."
        CONFIG_WRITTEN=1
        return 0
    fi

    mkdir -p "$CONFIG_DIR"
    backup_file "$CONFIG_FILE"
    # cat-over rather than `mv` from mktemp: mktemp creates 0600, and moving it
    # into place would silently tighten a normal 0644 config.
    cat "$tmp" > "$CONFIG_FILE"
    rm -f "$tmp"
    CONFIG_WRITTEN=1
    log_ok "$CONFIG_FILE written."
}

# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
#                                                          MAIN - LET'S GO!!!
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒
main() {
    check_for_root

    banner "GHOSTTY" "terminal · config"
    log_phase "PREFLIGHT"

    detect_package_manager
    setup_sudo
    log_info "OS=$OS  ARCH=$ARCH  PKG_MGR=$PKG_MGR"

    log_phase "PACKAGES"
    ensure_homebrew         # macOS: bootstrap brew BEFORE anything that uses it
    ensure_tool curl
    install_ghostty

    log_phase "CONFIG"
    write_example_config

    if (( GHOSTTY_INSTALLED )); then
        log_complete "GHOSTTY INSTALLED"
    else
        log_complete "NOTHING INSTALLED"
    fi
    if (( CONFIG_WRITTEN )); then
        log_next "Config:  $CONFIG_FILE   (docs: https://ghostty.org/docs/config)"
    else
        log_next "No config was written; ghostty will start with its defaults."
    fi
    log_next "Pick a theme:  ghostty +list-themes"
    log_next "Pick a font:   ghostty +list-fonts"
    log_next "If glyphs render as boxes, install the Nerd Fonts first:  ./install-nerd-fonts.sh"
    echo
}

main "$@"
