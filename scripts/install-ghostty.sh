#   - Arch / Manjaro               (pacman, [extra])
#   - Alpine                       (apk, testing)
#   - openSUSE                     (zypper, repo-oss)
#
# Usage:  ./install-ghostty.sh
# Do not run as root.
#
# The script is idempotent: rerunning it should not duplicate config or fail.
# ‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒‒

